"""Unit tests verifying structured JSON logging and context correlation."""

import json
import logging
from datetime import UTC, datetime

import pytest
from httpx import ASGITransport, AsyncClient

from ubuntubio.core.logging import (
    CorrelationFilter,
    JsonFormatter,
    get_logger,
    repo_slug_ctx,
    request_id_ctx,
    user_id_ctx,
)
from ubuntubio.main import app


def test_json_formatter_structure() -> None:
    """Verify JsonFormatter outputs valid JSON with GCP Cloud Logging severity and timestamp."""
    formatter = JsonFormatter()
    record = logging.LogRecord(
        name="ubuntubio.test",
        level=logging.INFO,
        pathname="test.py",
        lineno=10,
        msg="Test message with param: %s",
        args=("alpha",),
        exc_info=None,
    )
    record.created = datetime(2026, 10, 19, 12, 0, 0, tzinfo=UTC).timestamp()

    formatted_str = formatter.format(record)
    data = json.loads(formatted_str)

    assert data["severity"] == "INFO"
    assert data["logger"] == "ubuntubio.test"
    assert data["message"] == "Test message with param: alpha"
    assert data["timestamp"].startswith("2026-10-19T12:00:00")


def test_context_correlation_filter() -> None:
    """Verify CorrelationFilter injects active contextvars into LogRecord."""
    corr_filter = CorrelationFilter()
    formatter = JsonFormatter()

    token_req = request_id_ctx.set("req-xyz-123")
    token_user = user_id_ctx.set("usr-456")
    token_repo = repo_slug_ctx.set("african-genomics/malaria-vector")

    try:
        record = logging.LogRecord(
            name="ubuntubio.test_context",
            level=logging.WARNING,
            pathname="test.py",
            lineno=25,
            msg="Warning event",
            args=(),
            exc_info=None,
        )
        assert corr_filter.filter(record) is True

        formatted_str = formatter.format(record)
        data = json.loads(formatted_str)

        assert data["severity"] == "WARNING"
        assert data["request_id"] == "req-xyz-123"
        assert data["user_id"] == "usr-456"
        assert data["repo_slug"] == "african-genomics/malaria-vector"
    finally:
        request_id_ctx.reset(token_req)
        user_id_ctx.reset(token_user)
        repo_slug_ctx.reset(token_repo)


def test_custom_extra_fields_serialization() -> None:
    """Verify custom attributes passed via extra={...} are serialized."""
    formatter = JsonFormatter()
    logger = get_logger("ubuntubio.test_extra")

    record = logger.makeRecord(
        name="ubuntubio.test_extra",
        level=logging.INFO,
        fn="test.py",
        lno=40,
        msg="Operation completed",
        args=(),
        exc_info=None,
        extra={"duration_ms": 12.34, "sample_count": 42},
    )

    formatted_str = formatter.format(record)
    data = json.loads(formatted_str)

    assert data["duration_ms"] == 12.34
    assert data["sample_count"] == 42


@pytest.mark.asyncio
async def test_request_logging_middleware_injects_header() -> None:
    """Verify HTTP requests return X-Request-ID header generated by middleware."""
    transport = ASGITransport(app=app)
    async with AsyncClient(transport=transport, base_url="http://test") as client:
        response = await client.get("/healthz")

    assert response.status_code == 200
    assert "x-request-id" in response.headers
    assert len(response.headers["x-request-id"]) > 0


@pytest.mark.asyncio
async def test_request_logging_middleware_propagates_client_header() -> None:
    """Verify an existing X-Request-ID header from the client is propagated."""
    client_req_id = "client-trace-abc-789"
    transport = ASGITransport(app=app)
    async with AsyncClient(transport=transport, base_url="http://test") as client:
        response = await client.get("/healthz", headers={"X-Request-ID": client_req_id})

    assert response.status_code == 200
    assert response.headers.get("x-request-id") == client_req_id
